package lab6;

/**
 * Пирамидальная сортировка (heapsort).
 *
 * Задача 18:
 * Отсортировать последовательность так, чтобы вначале шли
 * отсортированные чётные элементы, а затем отсортированные нечётные.
 *
 * Все методы итеративные (без обёрток и рекурсии).
 */
public class HeapSort {

    // ================================================================
    // ПРОСЕИВАНИЕ ВНИЗ (heapify)
    // ================================================================
    /**
     * Восстанавливает свойство max-heap в поддереве с корнем i.
     *
     * Итеративная версия (без рекурсии).
     *
     * @param arr - массив
     * @param n - размер кучи
     * @param i - индекс корня поддерева
     */
    public static void heapify(int[] arr, int n, int i) {
        while (true) {
            int largest = i;
            int left = 2 * i + 1;
            int right = 2 * i + 2;

            // ищем наибольшего среди корня, левого и правого
            if (left < n && arr[left] > arr[largest]) {
                largest = left;
            }
            if (right < n && arr[right] > arr[largest]) {
                largest = right;
            }

            // если корень уже максимальный — выходим
            if (largest == i) {
                break;
            }

            // меняем корень с наибольшим
            int temp = arr[i];
            arr[i] = arr[largest];
            arr[largest] = temp;

            // продолжаем просеивать вниз
            i = largest;
        }
    }

    // ================================================================
    // ПОСТРОЕНИЕ КУЧИ (buildHeap)
    // ================================================================
    /**
     * Превращает произвольный массив в max-heap.
     *
     * @param arr - массив
     * @param n - размер массива
     */
    public static void buildHeap(int[] arr, int n) {
        // начинаем с последнего родителя
        for (int i = n / 2 - 1; i >= 0; i--) {
            heapify(arr, n, i);
        }
    }

    // ================================================================
    // ПИРАМИДАЛЬНАЯ СОРТИРОВКА
    // ================================================================
    /**
     * Сортирует массив по возрастанию пирамидальной сортировкой.
     *
     * @param arr - массив
     * @param n - размер массива
     */
    public static void heapSort(int[] arr, int n) {
        // 1. строим max-heap
        buildHeap(arr, n);

        // 2. по одному извлекаем максимум
        for (int i = n - 1; i > 0; i--) {
            // меняем корень (максимум) с последним
            int temp = arr[0];
            arr[0] = arr[i];
            arr[i] = temp;

            // восстанавливаем кучу для оставшихся
            heapify(arr, i, 0);
        }
    }

    // ================================================================
    // ЗАДАЧА 18
    // ================================================================
    /**
     * Задача 18.
     * Сортирует массив так, чтобы сначала шли отсортированные
     * чётные элементы, затем отсортированные нечётные.
     *
     * Алгоритм:
     * 1. Считаем количество чётных и нечётных.
     * 2. Создаём два массива: чётные и нечётные.
     * 3. Заполняем их.
     * 4. Сортируем каждый пирамидальной сортировкой.
     * 5. Склеиваем: сначала чётные, потом нечётные.
     *
     * @param arr - исходный массив
     * @return новый массив с результатом
     */
    public static int[] solveTask18(int[] arr) {
        int n = arr.length;

        // 1. считаем чётные и нечётные
        int evenCount = 0;
        int oddCount = 0;
        for (int i = 0; i < n; i++) {
            if (arr[i] % 2 == 0) {
                evenCount++;
            } else {
                oddCount++;
            }
        }

        // 2. создаём два массива
        int[] even = new int[evenCount];
        int[] odd = new int[oddCount];

        // 3. заполняем
        int eIdx = 0;
        int oIdx = 0;
        for (int i = 0; i < n; i++) {
            if (arr[i] % 2 == 0) {
                even[eIdx++] = arr[i];
            } else {
                odd[oIdx++] = arr[i];
            }
        }

        // 4. сортируем каждый
        heapSort(even, evenCount);
        heapSort(odd, oddCount);

        // 5. склеиваем
        int[] result = new int[n];
        for (int i = 0; i < evenCount; i++) {
            result[i] = even[i];
        }
        for (int i = 0; i < oddCount; i++) {
            result[evenCount + i] = odd[i];
        }

        return result;
    }
}